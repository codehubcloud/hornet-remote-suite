import { createRequire } from 'node:module';
import { mkdir,readFile,writeFile } from 'node:fs/promises';
import { createWriteStream,createReadStream } from 'node:fs';
import { pipeline } from 'node:stream/promises';
import { Readable } from 'node:stream';
import { createHash } from 'node:crypto';
import { dirname,join } from 'node:path';
const require=createRequire(import.meta.url);
const folder=dirname(require.resolve('electron/package.json'));
const {version}=require('electron/package.json');
if(process.platform!=='win32'||process.arch!=='x64')throw new Error('Use the official Electron installer on this platform.');
const file='electron-v'+version+'-win32-x64.zip';
await mkdir('.cache/electron',{recursive:true});
const archive=join('.cache/electron',file);
const response=await fetch('https://github.com/electron/electron/releases/download/v'+version+'/'+file);
if(!response.ok||!response.body)throw new Error('Electron download failed: '+response.status);
await pipeline(Readable.fromWeb(response.body),createWriteStream(archive));
const hash=createHash('sha256');
for await(const data of createReadStream(archive))hash.update(data);
const expected=JSON.parse(await readFile(join(folder,'checksums.json'),'utf8'))[file];
if(!expected||hash.digest('hex')!==expected)throw new Error('Electron checksum mismatch');
await require('@electron-internal/extract-zip').extract(archive,{dir:join(folder,'dist')});
await writeFile(join(folder,'path.txt'),'electron.exe');
console.log('Installed checksum-verified Electron '+version);
