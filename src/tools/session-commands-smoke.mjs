import { dismissStartupSessions } from './session-dialog-helper.mjs';
import { _electron as electron,expect } from '@playwright/test';
import { mkdtemp,rm,mkdir } from 'node:fs/promises';
import { join,resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
await mkdir('test-results',{recursive:true});
await build({entryPoints:['tests/fixtures/ssh-server.ts'],outfile:'test-results/commands-fixture.cjs',bundle:true,platform:'node',format:'cjs',external:['ssh2']});
const server=await createRequire(import.meta.url)(resolve('test-results/commands-fixture.cjs')).sshFixture();
const data=await mkdtemp(join(tmpdir(),'hornet-commands-'));
const env={...process.env,HORNET_USER_DATA:data,HORNET_SMOKE:'1'};delete env.ELECTRON_RUN_AS_NODE;
let app;
try{
 app=await electron.launch({args:['.'],env,timeout:30000});const page=await app.firstWindow();await dismissStartupSessions(page);page.setDefaultTimeout(15000);
 const menu=async(group,item)=>{await page.getByRole('navigation',{name:'应用菜单'}).getByRole('button',{name:group,exact:true}).click();await page.getByRole('menuitem',{name:item,exact:true}).click();};
 await page.getByLabel('快速连接地址',{exact:true}).fill('tester@127.0.0.1:'+server.port);
 await page.locator('.quick-connect-bar').getByRole('button',{name:'连接',exact:true}).click();
 await page.getByLabel('名称',{exact:true}).fill('Menu integration');
 await page.getByRole('button',{name:'保存并连接',exact:true}).click();
 await page.getByLabel('认证信息',{exact:true}).fill('test-password');
 await page.getByRole('button',{name:'继续连接',exact:true}).click();
 await page.getByRole('button',{name:'已核对，信任此主机',exact:true}).click();
 await expect(page.locator('.terminal-cell')).toHaveCount(1);
 await menu('编辑','重命名终端');
 await page.getByLabel('终端标题',{exact:true}).fill('菜单终端');
 await page.getByRole('button',{name:'保存标题',exact:true}).click();
 await expect(page.locator('.tabs')).toContainText('菜单终端');
 await menu('编辑','查找终端内容');
 await page.getByLabel('搜索终端内容').fill('fixture');
 await page.getByRole('button',{name:'下一个',exact:true}).click();
 await expect(page.getByText('已定位匹配',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'关闭终端搜索',exact:true}).click();
 await page.keyboard.press('Control+Shift+L');
 await expect(page.getByLabel('快速连接地址',{exact:true})).toBeFocused();
 await page.getByLabel('快速连接地址',{exact:true}).fill('Menu integration');
 await page.locator('.quick-connect-bar').getByRole('button',{name:'连接',exact:true}).click();
 await expect(page.locator('.terminal-cell')).toHaveCount(2);
 await menu('窗口','垂直分割');
 await expect(page.locator('.terminal-cell:visible')).toHaveCount(2);
 if(server.shellCount!==2||server.authCount!==1)throw new Error('Menu layout created an extra shell or transport');
 await menu('查看','折叠工具栏');await expect(page.locator('.session-commands')).toBeHidden();
 await page.getByRole('button',{name:'展开工具栏',exact:true}).click();
 await expect(page.getByLabel('快速连接地址',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/session-commands.png'});
 console.log('Session command smoke passed: address/save/connect, saved session, search, rename, split, toolbar collapse.');
}finally{
 if(app)await app.evaluate(({app})=>app.exit(0));
 await server.close();await rm(data,{recursive:true,force:true,maxRetries:5,retryDelay:200});
}
